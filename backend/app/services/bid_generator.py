"""标书生成 Pipeline"""

import json
from ..llm.openai_compat import OpenAICompatibleLLM


async def generate_chapter(
    chapter_title: str,
    chapter_index: int,
    tender_context: str,
    rag_context: str = "",
) -> str:
    """生成单个标书章节，返回完整内容"""
    llm = OpenAICompatibleLLM()

    prompt = f"""请根据以下信息撰写标书章节。

## 章节信息
- 章节名称：{chapter_title}

## 招标文件解读结果（作为依据）
{tender_context}

## 知识库参考
{rag_context if rag_context else "（无相关知识库参考）"}

直接输出该章节的正文内容，不要加任何开场白、自我介绍、确认语句或结尾总结。只写标书正文。语言正式、条理清晰，符合招投标文件的编写规范。

## 重要：占位符使用规则

在撰写正文时，凡是涉及投标人（即我方）的具体信息，必须使用双花括号占位符 `{{{{字段名}}}}` 代替，不得编造任何具体值。常见占位符包括但不限于：

- 公司信息：{{{{公司名称}}}}、{{{{法定代表人}}}}、{{{{注册资本}}}}、{{{{成立日期}}}}、{{{{营业执照号}}}}、{{{{统一社会信用代码}}}}、{{{{公司地址}}}}、{{{{联系电话}}}}、{{{{开户银行}}}}、{{{{银行账号}}}}
- 人员信息：{{{{项目负责人}}}}、{{{{技术负责人}}}}、{{{{授权代表}}}}
- 财务/商务：{{{{投标总价}}}}、{{{{投标保证金金额}}}}、{{{{工期}}}}、{{{{质保期}}}}
- 项目相关：{{{{项目名称}}}}、{{{{项目编号}}}}、{{{{招标人名称}}}}

规则：
1. 凡是无法从招标文件解读结果中确定的、属于"我方"的具体信息，一律使用占位符
2. 占位符名称使用中文描述，简明扼要，见名知义
3. 可从招标文件解读结果中确定的客观信息（如招标人名称、项目名称）则直接使用实际值
4. 技术方案、实施方案等描述性内容正常撰写，不涉及占位符
5. 占位符前后不要添加任何修饰字符"""

    messages = [
        {"role": "system", "content": "你是标书撰写专家，直接输出标书章节正文，不输出任何对话性内容、问候语、确认语。凡是涉及我方公司具体信息（公司名称、法定代表人、注册资本、报价金额、项目负责人姓名等），必须使用双花括号占位符 {{{{字段名}}}} 代替，严禁编造任何具体值。"},
        {"role": "user", "content": prompt},
    ]

    result = await llm.chat_complete(messages)
    await llm.close()
    return result


async def generate_chapter_stream(
    chapter_title: str,
    chapter_index: int,
    tender_context: str,
    rag_context: str = "",
):
    """流式生成标书章节"""
    llm = OpenAICompatibleLLM()

    prompt = f"""请根据以下信息撰写标书章节。

## 章节信息
- 章节名称：{chapter_title}

## 招标文件解读结果（作为依据）
{tender_context}

## 知识库参考
{rag_context if rag_context else "（无相关知识库参考）"}

直接输出该章节的正文内容，不要加任何开场白、自我介绍、确认语句或结尾总结。只写标书正文。语言正式、条理清晰，符合招投标文件的编写规范。

## 重要：占位符使用规则

在撰写正文时，凡是涉及投标人（即我方）的具体信息，必须使用双花括号占位符 `{{{{字段名}}}}` 代替，不得编造任何具体值。常见占位符包括但不限于：

- 公司信息：{{{{公司名称}}}}、{{{{法定代表人}}}}、{{{{注册资本}}}}、{{{{成立日期}}}}、{{{{营业执照号}}}}、{{{{统一社会信用代码}}}}、{{{{公司地址}}}}、{{{{联系电话}}}}、{{{{开户银行}}}}、{{{{银行账号}}}}
- 人员信息：{{{{项目负责人}}}}、{{{{技术负责人}}}}、{{{{授权代表}}}}
- 财务/商务：{{{{投标总价}}}}、{{{{投标保证金金额}}}}、{{{{工期}}}}、{{{{质保期}}}}
- 项目相关：{{{{项目名称}}}}、{{{{项目编号}}}}、{{{{招标人名称}}}}

规则：
1. 凡是无法从招标文件解读结果中确定的、属于"我方"的具体信息，一律使用占位符
2. 占位符名称使用中文描述，简明扼要，见名知义
3. 可从招标文件解读结果中确定的客观信息（如招标人名称、项目名称）则直接使用实际值
4. 技术方案、实施方案等描述性内容正常撰写，不涉及占位符
5. 占位符前后不要添加任何修饰字符"""

    messages = [
        {"role": "system", "content": "你是标书撰写专家，直接输出标书章节正文，不输出任何对话性内容、问候语、确认语。凡是涉及我方公司具体信息（公司名称、法定代表人、注册资本、报价金额、项目负责人姓名等），必须使用双花括号占位符 {{{{字段名}}}} 代替，严禁编造任何具体值。"},
        {"role": "user", "content": prompt},
    ]

    full = ""
    async for token in llm.chat(messages, stream=True):
        full += token
        yield json.dumps({"type": "chunk", "content": token}, ensure_ascii=False) + "\n"

    yield json.dumps({"type": "done", "content": full}, ensure_ascii=False) + "\n"
    await llm.close()
